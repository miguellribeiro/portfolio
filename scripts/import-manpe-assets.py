"""Import the reviewed SVG package as static, typed React markup (no runtime parsing)."""
from pathlib import Path
import json
import shutil
import xml.etree.ElementTree as ET

source = Path(r'C:\Users\Dev 01\agentes\pessoal-2\shared\manpe-assets')
target = Path('packages/ui/manpe/assets')
target.mkdir(parents=True, exist_ok=True)
for asset in source.iterdir():
    if asset.is_file():
        shutil.copyfile(asset, target / asset.name)

def camel(name):
    parts = name.split('-')
    return parts[0] + ''.join(p.title() for p in parts[1:])

def jsx(node, depth=2):
    tag = node.tag.split('}')[-1]
    attrs = []
    for key, value in node.attrib.items():
        if key == 'style':
            value = {camel(k.strip()): v.strip() for k, v in
                     (part.split(':', 1) for part in value.split(';') if part.strip())}
            attrs.append('style={' + json.dumps(value) + '}')
        else:
            key = key if key.startswith(('data-', 'aria-')) else camel(key)
            attrs.append(key + '=' + json.dumps(value))
    start = '  ' * depth + '<' + tag + (' ' + ' '.join(attrs) if attrs else '')
    if not len(node):
        return start + ' />'
    return start + '>\n' + '\n'.join(jsx(child, depth + 1) for child in node) + '\n' + '  ' * depth + '</' + tag + '>'

components = ['// Generated by scripts/import-manpe-assets.py from the reviewed package.\n']
for name in ['monkey', 'capybara', 'bird', 'vegetation']:
    root = ET.parse(target / (name + '.svg')).getroot()
    root.tag = 'g'
    root.attrib = {k: v for k, v in root.attrib.items() if k in ('fill', 'style')}
    components.append('export function ' + name.title() + 'Artwork() {\n  return (\n' + jsx(root) + '\n  );\n}\n')
Path('packages/ui/manpe/Artwork.tsx').write_text('\n'.join(components), encoding='utf-8')
